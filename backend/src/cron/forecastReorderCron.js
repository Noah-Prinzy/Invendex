import cron from 'node-cron';
import { runReorderEngine } from '../services/reorderEngine.js';

let cronStarted = false;

/**
 * 🔁 Forecast-aware reorder automation cron
 *
 * Runs daily at 00:40
 *
 * Responsibilities:
 * - Invoke reorder engine
 * - Let engine decide FORECAST vs STATIC logic
 * - Persist reorder alerts
 *
 * IMPORTANT:
 * - No business logic here
 * - No DB queries here
 * - Safe to run multiple times (idempotent)
 */
export const startForecastReorderCron = () => {
  if (cronStarted) return;
  cronStarted = true;

  console.log('⏱️ Forecast reorder cron scheduled (daily at 00:40)');

  cron.schedule('40 0 * * *', async () => {
    try {
      console.log('🔁 Running forecast-aware reorder cron...');

      const alerts = await runReorderEngine({
        triggeredBy: 'CRON_FORECAST'
      });

      if (alerts.length > 0) {
        console.warn(
          `⚠️ ${alerts.length} reorder alert(s) generated by forecast engine`
        );
      } else {
        console.log('✅ No reorder alerts needed');
      }
    } catch (err) {
      console.error(
        '❌ Forecast reorder cron failed:',
        err
      );
    }
  });
};